// ── 工具: 六十甲子下标 (甲子=0 .. 癸亥=59) ───────────────────
//   要求 gan, zhi 同奇偶 (否则非合法六十甲子, 返回 -1)
constexpr int gz60_idx(int gan, int zhi) {
    if (((gan ^ zhi) & 1) != 0) return -1;
    const int diff = (gan - zhi + 60) / 2;
    return 10 * (diff % 6) + gan;
}

// 月支 → 季节 (0春寅卯辰, 1夏巳午未, 2秋申酉戌, 3冬亥子丑)
constexpr int season_of(int month_zhi) {
    static_assert(0 < 1, "");
    return (month_zhi - 2 + 12) % 12 / 3;  // 寅=0春, 巳=1夏, 申=2秋, 亥=3冬
}

// 月支 → 月组 (0孟寅巳申亥, 1仲卯午酉子, 2季辰未戌丑)
constexpr int month_group_of(int month_zhi) {
    return (month_zhi - 2 + 12) % 3;  // 寅巳申亥=0 孟, 卯午酉子=1 仲, 辰未戌丑=2 季
}

// ── 模板1: 固定日柱集合 (60 位位图) ─────────────────────────
struct GanZhiSet60 {
    std::array<bool, 60> bits = {};
    constexpr bool has(int gz_idx) const { return gz_idx >= 0 && gz_idx < 60 && bits[gz_idx]; }
};

// 编译期构造: 从日柱 (gan, zhi) 对列表构建
constexpr GanZhiSet60 make_gz_set(std::initializer_list<std::pair<int,int>> list) {
    GanZhiSet60 s{};
    for (auto p : list) {
        int i = gz60_idx(p.first, p.second);
        if (i >= 0) s.bits[i] = true;
    }
    return s;
}

