Vector3 epSSB(long double t)
{
    t /= 10.0L;   // JS: t /= 10
    long double x = 0, y = 0, z = 0;
    for (int i = 0; i + 5 < EP_TAB_COUNT; i += 6)
    {
        x += epTab[i + 0] * std::cos(epTab[i + 1] + epTab[i + 2] * t);
        y += epTab[i + 3] * std::cos(epTab[i + 4] + epTab[i + 5] * t);
    }
    x += t * (1234.0L
            + 515.0L * std::cos(6.002663L + 12566.1517L  * t)
            +  13.0L * std::cos(5.959431L + 18849.22755L * t)
            +  11.0L * std::cos(2.015542L +  6283.07585L * t));
    y += t * ( 930.0L
            + 515.0L * std::cos(4.431805L + 12566.1517L  * t)
            +  13.0L * std::cos(4.388605L + 18849.22755L * t));
    z += t * (  54.0L
            + 2278.0L * std::cos(3.413725L +  6283.07585L  * t)
            +   19.0L * std::cos(3.370613L + 12566.15170L * t));
    constexpr long double M = 1.0L / 1000000.0L;
    x *= M; y *= M; z *= M;

    // 旋转到 J2000 赤道坐标系: 黄赤交角 E = -84381.448" (注意符号)
    const long double E = -84381.448L / static_cast<long double>(rad);
    long double yr = z * std::sin(E) + y * std::cos(E);
    long double zr = z * std::cos(E) - y * std::sin(E);
    return Vector3{x, yr, zr};
}

// ═══════════════════════════════════════════════════════════════
//  引力偏转
// ═══════════════════════════════════════════════════════════════
Vector3 ylpz(const Vector3 &z, const Vector3 &a)
{
    Vector3 r{z[0], z[1], z[2]};
    long double d = z[0] - a[0];
    long double D = std::sin(z[1]) * std::sin(a[1])
                  + std::cos(z[1]) * std::cos(a[1]) * std::cos(d);
    // JS: D = 0.00407 * (1/(1-D) + D/2) / rad
    D = 0.00407L * (1.0L / (1.0L - D) + D / 2.0L) / static_cast<long double>(rad);
    r[0] += D * (std::cos(a[1]) * std::sin(d) / std::cos(z[1]));
    r[1] += D * (std::sin(z[1]) * std::cos(a[1]) * std::cos(d)
              -  std::sin(a[1]) * std::cos(z[1]));
    r[0] = rad2mrad(r[0]);
    return r;
}

// ═══════════════════════════════════════════════════════════════
//  视差 / 光行差
// ═══════════════════════════════════════════════════════════════
Vector3 scGxc(const Vector3 &z, const Vector3 &v, bool parallax)
{
    Vector3 r{z[0], z[1], z[2]};
    // 光速 AU/儒略世纪 = cs_GS(km/s) / cs_AU(km) * 86400 * 36525
    long double c = static_cast<long double>(cs_GS) / static_cast<long double>(cs_AU)
                  * 86400.0L * 36525.0L;
    if (parallax) c = -z[2];          // 求视差时, 距离取负 (r-v)

    long double sinJ = std::sin(z[0]), cosJ = std::cos(z[0]);
    long double sinW = std::sin(z[1]), cosW = std::cos(z[1]);
    r[0] += rad2mrad((v[1] * cosJ - v[0] * sinJ) / cosW / c);
    r[1] += (v[2] * cosW - (v[0] * cosJ + v[1] * sinJ) * sinW) / c;
    return r;
}

// ═══════════════════════════════════════════════════════════════
//  太阳 J2000 球面坐标
// ═══════════════════════════════════════════════════════════════
Vector3 sun2000(long double t, int n)
{
    // 太阳 Date 黄道坐标 = 地球的相反方向
    Vector3 a = e_coord(t, n, n, n);
    a[0] += static_cast<long double>(PI);
    a[1] = -a[1];
    // 转回 J2000 黄道
    a = HDllr_D2J(t, a, std::string("P03"));
    return a;
}

