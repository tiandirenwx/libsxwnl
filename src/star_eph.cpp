static constexpr int EV_TAB_ROWS = 39;
static constexpr int EV_TAB_COLS = 12;

Vector3 evSSB(long double t)
{
    // 11 个基本角参数 (弧度), 与 ephB.js 完全一致
    const long double J[11] = {
        3.1761467L + 1021.3285546L  * t,   // 金
        1.7534703L +  628.3075849L  * t,   // 地
        6.2034809L +  334.0612431L  * t,   // 火
        0.5995465L +   52.9690965L  * t,   // 木
        0.8740168L +   21.3299095L  * t,   // 土
        5.4812939L +    7.4781599L  * t,   // 天
        5.3118863L +    3.8133036L  * t,   // 海
        3.8103444L + 8399.6847337L  * t,   // 月 L'
        5.1984667L + 7771.3771486L  * t,   // 月 D
        2.3555559L + 8328.6914289L  * t,   // 月 M'
        1.6279052L + 8433.4661601L  * t,   // 月 F
    };

    long double vx = 0, vy = 0, vz = 0;
    for (int i = 0; i < EV_TAB_ROWS; ++i)
    {
        const long double *row = evTab + i * EV_TAB_COLS;
        long double Tn = (i >= 36) ? t : 1.0L;     // 末 3 行为泊松项
        // 注意: JS 中 F[k] * J[F[k+1]] —— 这里 row[0..5] 是 (倍数, J 索引) 对
        int idx1 = (int)row[1];
        int idx2 = (int)row[3];
        int idx3 = (int)row[5];
        long double c = row[0] * J[idx1]
                      + row[2] * J[idx2]
                      + row[4] * J[idx3];
        long double S = std::sin(c);
        long double C = std::cos(c);
        vx += (row[6]  * S + row[7]  * C) * Tn;
        vy += (row[8]  * S + row[9]  * C) * Tn;
        vz += (row[10] * S + row[11] * C) * Tn;
    }
    // JS: v[i] *= 0.00036525  (单位: AU/世纪, 系数 1e-8 × 36525 = 3.6525e-4)
    constexpr long double SCALE = 0.00036525L;
    return Vector3{vx * SCALE, vy * SCALE, vz * SCALE};
}

